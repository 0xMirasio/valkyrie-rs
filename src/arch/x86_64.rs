pub fn set_reg<D>(uc: &mut Unicorn<'_, D>, reg: RegX86_64, value: u64) -> Result<()> {
    uc.reg_write(to_uc(reg), value)?;
    Ok(())
}

pub fn get_reg<D>(uc: &mut Unicorn<'_, D>, reg: RegX86_64) -> Result<u64> {
    Ok(uc.reg_read(to_uc(reg))?)
}
